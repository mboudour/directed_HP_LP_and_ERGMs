#!/usr/bin/env python3
"""Assemble the canonical Markdown Paper 1 draft from tracked sections and tables."""

from __future__ import annotations

import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MANUSCRIPT_DIR = PROJECT_ROOT / "manuscript"
SECTIONS_DIR = MANUSCRIPT_DIR / "sections"
TABLES_DIR = MANUSCRIPT_DIR / "tables"
OUTPUT_PATH = MANUSCRIPT_DIR / "PAPER1_DRAFT.md"

SECTION_ORDER = [
    "00_title_abstract.md",
    "01_introduction.md",
    "02_target_ladder_and_score_logic.md",
    "03_data_and_methods.md",
    "05_results.md",
    "06_discussion.md",
]
TABLE_ORDER = [
    "table_01_dataset_target_eligibility.md",
    "table_02_concept_event_fidelity.md",
    "table_03a_primary_native_random_panel_pr_auc.md",
    "table_03b_primary_native_hard_panel_pr_auc.md",
    "table_03c_primary_native_role_assignment.md",
    "table_04_paired_ergm_random_panel_pr_auc.md",
    "table_05_bounded_temporal_diagnostic.md",
    "table_06_pilot_gates_and_exclusions.md",
]


def require_text(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"required manuscript input is missing: {path}")
    return path.read_text().strip()


def strip_introduction_references(text: str) -> str:
    return re.sub(r"\n## References\n.*\Z", "", text, flags=re.DOTALL).strip()


def table_body(text: str) -> str:
    return re.sub(r"(?m)^# (?!#)", "## ", text).strip()


def main() -> None:
    sections: list[str] = []
    for name in SECTION_ORDER:
        content = require_text(SECTIONS_DIR / name)
        if name == "01_introduction.md":
            content = strip_introduction_references(content)
        sections.append(content)

    tables = [table_body(require_text(TABLES_DIR / name)) for name in TABLE_ORDER]
    references = require_text(PROJECT_ROOT / "docs" / "MANUSCRIPT_LITERATURE_SOURCES.md")
    reference_definitions = references.split("## References\n", maxsplit=1)[1].strip()

    output = "\n\n".join(
        [
            (
                "<!-- Generated by scripts/54_build_paper1_markdown.py; do not edit "
                "this file directly. -->"
            ),
            *sections,
            "# Main tables\n\n"
            "The tables below are generated from aggregate-only Phase 2 outputs by "
            "`scripts/53_build_manuscript_tables.py`. Their Markdown layout is a review "
            "format rather than a journal submission format.",
            "\n\n".join(tables),
            "# References\n\n" + reference_definitions,
        ]
    )
    OUTPUT_PATH.write_text(output + "\n")
    print(f"Canonical Markdown draft written: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
