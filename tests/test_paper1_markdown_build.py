"""Regression checks for the canonical Markdown manuscript assembly."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
BUILDER = PROJECT_ROOT / "scripts" / "54_build_paper1_markdown.py"
OUTPUT = PROJECT_ROOT / "manuscript" / "PAPER1_DRAFT.md"


def test_paper1_markdown_builder_assembles_sections_and_tables() -> None:
    subprocess.run(
        [sys.executable, str(BUILDER)],
        cwd=PROJECT_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )

    text = OUTPUT.read_text()
    assert text.startswith("<!-- Generated by scripts/54_build_paper1_markdown.py")
    assert "# Introduction" in text
    assert "# Results" in text
    assert "# Main tables" in text
    assert "M4c::L1g − M0::L1" in text
    assert text.count("# References") == 1
